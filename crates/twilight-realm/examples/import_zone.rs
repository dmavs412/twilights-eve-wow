//! Writes `content/duskwood.toml`, `content/redridge.toml` and `content/stormwind.toml`, the
//! realm's copies of Duskwood, Redridge Mountains and Stormwind City's spawns (spec #466), from
//! their dumps in `data/twilights-eve/` (every creature spawn of the zone, friendly NPCs included,
//! imported from the vmangos world DB by `tools/twilights-eve/import_barrens_spawns.py
//! --all-creatures`). `import_elwynn.rs` shares the conversion.
//!
//! As in Elwynn there are no rings and no camp regrouping: every spawn keeps its vmangos place and
//! levels and is a camp of its own. Combat stats come from the realm's tables by level, as for
//! every mob.
//!
//! ```text
//! cargo run -p twilight-realm --example import_zone
//! ```
//!
//! `tests/content_zones.rs` fails when a committed file no longer matches its dump.
//! `docs/reference/zone-spawns.md` has the whole chain.

#[path = "import_barrens.rs"]
#[allow(dead_code)]
mod import_barrens;

use std::path::PathBuf;

use import_barrens::{pick_display, reaction, row, template_with};
use serde_json::Value;

/// One imported zone: its dump in `data/twilights-eve/`, its file in `content/`, the example,
/// test and doc its header names, and the entries whose spawns moved to `content/hub.toml`.
pub struct Zone {
    pub name: &'static str,
    pub dump: &'static str,
    pub toml: &'static str,
    pub example: &'static str,
    pub test: &'static str,
    pub doc: &'static str,
    pub hub_npcs: &'static [u64],
}

/// The zones this example writes.
pub const ZONES: &[Zone] = &[
    Zone {
        name: "Duskwood",
        dump: "duskwood_spawns.json",
        toml: "duskwood.toml",
        example: "import_zone",
        test: "tests/content_zones.rs",
        doc: "docs/reference/zone-spawns.md",
        hub_npcs: &[],
    },
    Zone {
        name: "Redridge Mountains",
        dump: "redridge_spawns.json",
        toml: "redridge.toml",
        example: "import_zone",
        test: "tests/content_zones.rs",
        doc: "docs/reference/zone-spawns.md",
        // Alma Jainrose teaches Herbalism.
        hub_npcs: &[812],
    },
    Zone {
        name: "Stormwind City",
        dump: "stormwind_spawns.json",
        toml: "stormwind.toml",
        example: "import_zone",
        test: "tests/content_zones.rs",
        doc: "docs/reference/zone-spawns.md",
        // Shylamiir and Tannysa teach Herbalism.
        hub_npcs: &[5502, 5566],
    },
];

fn krate() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

/// Reads the zone's dump.
pub fn dump(zone: &Zone) -> Value {
    let path = krate().join("../../data/twilights-eve").join(zone.dump);
    let text = std::fs::read_to_string(path).expect("the dump reads");
    serde_json::from_str(&text).expect("the dump parses")
}

/// The zone's committed file.
pub fn output_path(zone: &Zone) -> PathBuf {
    krate().join("content").join(zone.toml)
}

/// The zone's file from its dump, leaving out the spawns of every entry in `zone.hub_npcs`.
pub fn convert(zone: &Zone, dump: &Value) -> String {
    let mut out = format!(
        "# GENERATED by `cargo run -p twilight-realm --example {}` from\n\
         # data/twilights-eve/{} (the vmangos world DB). Do not edit:\n\
         # {} fails when this file and the dump disagree.\n\
         # {} says how to re-run it all.\n\n\
         # One row per spawn: [guid, entry, level_min, level_max, x, y, z, orientation, display_id,\n\
         # wander_radius, camp]. WoW coordinates on Eastern Kingdoms (map 0); every spawn is a camp\n\
         # of its own.\n\
         spawns = [\n",
        zone.example, zone.dump, zone.test, zone.doc,
    );
    let templates = &dump["templates"];
    let spawns: Vec<&Value> = dump["spawns"]
        .as_array()
        .expect("spawns")
        .iter()
        .filter(|s| !zone.hub_npcs.contains(&s["entry"].as_u64().unwrap()))
        .collect();
    for s in &spawns {
        let guid = s["guid"].as_u64().unwrap();
        let entry = s["entry"].as_u64().unwrap();
        let display = pick_display(
            &templates[entry.to_string()],
            guid,
            s["display_id"].as_u64().unwrap(),
        );
        row(&mut out, s, display, guid);
    }
    out.push_str("]\n");

    let mut entries: Vec<u64> = spawns
        .iter()
        .map(|s| s["entry"].as_u64().unwrap())
        .collect();
    entries.sort_unstable();
    entries.dedup();
    for entry in entries {
        let t = &templates[entry.to_string()];
        let hostile = reaction(dump, entry) && !t["no_aggro"].as_bool().unwrap_or(false);
        let levels = [&t["level_min"], &t["level_max"]].map(|l| l.as_u64().unwrap());
        let friendly = friendly(dump, entry).then_some(FRIENDLY_TO_ALL);
        template_with(&mut out, entry, t, hostile, levels, friendly);
    }
    out
}

/// `FactionTemplate.dbc` 35, friendly to every player race. The imported zones' NPCs show it
/// whatever the player's race (spec #71): the guards, vendors and trainers are everyone's friends.
const FRIENDLY_TO_ALL: u64 = 35;

/// Whether the entry's spawns are friendly to a player faction (they share one faction template,
/// so they agree).
fn friendly(dump: &Value, entry: u64) -> bool {
    dump["spawns"]
        .as_array()
        .unwrap()
        .iter()
        .find(|s| s["entry"].as_u64() == Some(entry))
        .is_some_and(|s| s["reaction"] == "friendly")
}

#[allow(dead_code)]
fn main() {
    for zone in ZONES {
        let out = output_path(zone);
        std::fs::write(&out, convert(zone, &dump(zone))).expect("the zone file writes");
        println!("wrote {}", out.display());
    }
}
