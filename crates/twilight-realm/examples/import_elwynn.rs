//! Writes `content/elwynn.toml`, the realm's copy of Elwynn Forest's spawns, from
//! `data/twilights-eve/elwynn_spawns.json` (every creature spawn of the zone, friendly NPCs
//! included, imported from the vmangos world DB by `tools/twilights-eve/import_barrens_spawns.py
//! --all-creatures`).
//!
//! Unlike The Barrens there are no rings and no camp regrouping: every spawn keeps its vmangos
//! place and levels and is a camp of its own. Combat stats come from the realm's tables by level,
//! as for every mob.
//!
//! ```text
//! cargo run -p twilight-realm --example import_elwynn
//! ```
//!
//! `tests/content_elwynn.rs` fails when the committed file no longer matches the dump.
//! `docs/reference/elwynn-spawns.md` has the whole chain.

#[path = "import_barrens.rs"]
#[allow(dead_code)]
mod import_barrens;

use std::path::PathBuf;

use import_barrens::{pick_display, reaction, row, template};
use serde_json::Value;

fn krate() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

/// Reads the dump.
pub fn dump() -> Value {
    let path = krate().join("../../data/twilights-eve/elwynn_spawns.json");
    let text = std::fs::read_to_string(path).expect("the dump reads");
    serde_json::from_str(&text).expect("the dump parses")
}

/// The committed file's path.
pub fn output_path() -> PathBuf {
    krate().join("content/elwynn.toml")
}

/// `elwynn.toml` from the dump.
pub fn convert(elwynn: &Value) -> String {
    let mut out = String::from(
        "# GENERATED by `cargo run -p twilight-realm --example import_elwynn` from\n\
         # data/twilights-eve/elwynn_spawns.json (the vmangos world DB). Do not edit:\n\
         # tests/content_elwynn.rs fails when this file and the dump disagree.\n\
         # docs/reference/elwynn-spawns.md says how to re-run it all.\n\n\
         # One row per spawn: [guid, entry, level_min, level_max, x, y, z, orientation, display_id,\n\
         # wander_radius, camp]. WoW coordinates on Eastern Kingdoms (map 0); every spawn is a camp\n\
         # of its own.\n\
         spawns = [\n",
    );
    let templates = &elwynn["templates"];
    let spawns = elwynn["spawns"].as_array().expect("spawns");
    for s in spawns {
        let guid = s["guid"].as_u64().unwrap();
        let entry = s["entry"].as_u64().unwrap();
        let display = pick_display(
            &templates[entry.to_string()],
            guid,
            s["display_id"].as_u64().unwrap(),
        );
        row(&mut out, s, display, guid);
    }
    out.push_str("]\n");

    let mut entries: Vec<u64> = spawns
        .iter()
        .map(|s| s["entry"].as_u64().unwrap())
        .collect();
    entries.sort_unstable();
    entries.dedup();
    for entry in entries {
        let t = &templates[entry.to_string()];
        let hostile = reaction(elwynn, entry) && !t["no_aggro"].as_bool().unwrap_or(false);
        let levels = [&t["level_min"], &t["level_max"]].map(|l| l.as_u64().unwrap());
        template(&mut out, entry, t, hostile, levels);
    }
    out
}

#[allow(dead_code)]
fn main() {
    let out = output_path();
    std::fs::write(&out, convert(&dump())).expect("elwynn.toml writes");
    println!("wrote {}", out.display());
}
