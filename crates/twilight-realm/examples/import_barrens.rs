//! Writes `content/barrens.toml`, the realm's copy of The Barrens' spawns, from the research
//! dumps in `data/twilights-eve/`:
//!
//! - `barrens_spawns.json`: every hostile and neutral spawn of the zone, imported from the vmangos
//!   world DB by `tools/twilights-eve/import_barrens_spawns.py`, with its creature templates and
//!   camps;
//! - `crossroads_low_camps.json`: the hand-placed level 1–6 camps by the Crossroads
//!   (`tools/twilights-eve/make_crossroads_low_camps.py`), and the imported spawns they replace.
//!
//! On the way it filters the imported spawns into the rings ([`filter`]): levels rise outward
//! from the Crossroads and stop at 30.
//!
//! ```text
//! cargo run -p twilight-realm --example import_barrens
//! ```
//!
//! The realm reads TOML only (the shipped app keeps `serde_json` out), so this is the step from
//! the dumps to the realm. The output is deterministic and committed; `tests/content.rs` fails
//! when it no longer matches the dumps. `docs/reference/barrens-spawns.md` has the whole chain.

use std::fmt::Write as _;
use std::path::PathBuf;

use serde_json::Value;

/// The realm's content directory and the dumps' directory, from the crate root.
fn paths() -> (PathBuf, PathBuf) {
    let krate = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    (
        krate.join("content/barrens.toml"),
        krate.join("../../data/twilights-eve"),
    )
}

/// Reads the two dumps.
pub fn dumps() -> (Value, Value) {
    let (_, data) = paths();
    let read = |name: &str| -> Value {
        let text = std::fs::read_to_string(data.join(name)).expect("the dump reads");
        serde_json::from_str(&text).expect("the dump parses")
    };
    (
        read("barrens_spawns.json"),
        read("crossroads_low_camps.json"),
    )
}

/// The committed file's path.
pub fn output_path() -> PathBuf {
    paths().0
}

/// `barrens.toml` from the two dumps.
pub fn convert(barrens: &Value, low: &Value) -> String {
    let mut out = String::new();
    out.push_str(
        "# GENERATED by `cargo run -p twilight-realm --example import_barrens` from\n\
         # data/twilights-eve/barrens_spawns.json (the vmangos world DB) and\n\
         # data/twilights-eve/crossroads_low_camps.json. Do not edit: tests/content.rs fails when this\n\
         # file and the dumps disagree. docs/reference/barrens-spawns.md says how to re-run it all.\n\n",
    );

    let camps = low["camps"].as_array().expect("low camps");
    let filtered = filter(barrens, low);
    out.push_str(
        "# The rings: the imported spawns are filtered (`import_barrens.rs`'s `filter`) so that levels\n\
         # rise outward from the Crossroads and stop at the level cap. Left out of the dump's spawns:\n",
    );
    for (cut, n) in &filtered.cut {
        let _ = writeln!(out, "# - {n} {}", cut.describe());
    }
    let _ = writeln!(
        out,
        "# The Razorfen edge's quilboar ({RAZORFEN_QUILBOAR:?}) are retuned to levels {}-{}, The\n\
         # Barrens' capstone.\n",
        RAZORFEN_LEVELS[0], RAZORFEN_LEVELS[1]
    );

    out.push_str(
        "# One row per spawn: [guid, entry, level_min, level_max, x, y, z, orientation, display_id,\n\
         # wander_radius, camp]. WoW coordinates on Kalimdor; z is the dump's (vmangos spawn height, or\n\
         # the terrain under a low camp member). A camp is numbered by its lowest member guid.\n\
         spawns = [\n",
    );
    let templates = &barrens["templates"];
    for s in &filtered.kept {
        let entry = s["entry"].as_u64().unwrap();
        let display = pick_display(
            &templates[entry.to_string()],
            s["guid"].as_u64().unwrap(),
            s["display_id"].as_u64().unwrap(),
        );
        row(&mut out, s, display, s["camp_id"].as_u64().unwrap());
    }
    out.push_str("  # The low camps by the Crossroads.\n");
    for camp in camps {
        let members = camp["members"].as_array().unwrap();
        let id = members
            .iter()
            .map(|m| m["guid"].as_u64().unwrap())
            .min()
            .unwrap();
        for m in members {
            row(&mut out, m, m["display_id"].as_u64().unwrap(), id);
        }
    }
    out.push_str("]\n");

    // The imported creature templates, by entry. The low camps' are hand-written in mobs.toml.
    let mut entries: Vec<u64> = filtered
        .kept
        .iter()
        .map(|s| s["entry"].as_u64().unwrap())
        .collect();
    entries.sort_unstable();
    entries.dedup();
    for entry in entries {
        let t = &templates[entry.to_string()];
        let [lmin, lmax] = if RAZORFEN_QUILBOAR.contains(&entry) {
            RAZORFEN_LEVELS
        } else {
            [&t["level_min"], &t["level_max"]].map(|l| l.as_u64().unwrap())
        };
        let hostile = reaction(barrens, entry) && !t["no_aggro"].as_bool().unwrap_or(false);
        let _ = write!(
            out,
            "\n[[template]]\n\
             entry = {entry}\n\
             name = {name}\n\
             subname = {subname}\n\
             creature_type = {creature_type}\n\
             rank = {rank}\n\
             display_id = {display}\n\
             faction_template = {faction}\n\
             hostile = {hostile}\n\
             unit_class = \"{class}\"\n\
             level_min = {lmin}\n\
             level_max = {lmax}\n\
             health_multiplier = {hm:?}\n\
             damage_multiplier = {dm:?}\n\
             armor_multiplier = {am:?}\n\
             base_attack_time = {bat}\n\
             speed_walk = {sw:?}\n\
             speed_run = {sr:?}\n\
             detection_range = {det:?}\n",
            name = quoted(t["name"].as_str().unwrap()),
            subname = quoted(t["subname"].as_str().unwrap_or("")),
            creature_type = creature_type(t["type"].as_str().unwrap()),
            rank = rank(t["rank"].as_str().unwrap()),
            display = most_likely_display(t),
            faction = t["faction_template"].as_u64().unwrap(),
            class = unit_class(t["unit_class"].as_u64().unwrap()),
            hm = f32_of(&t["health_multiplier"]),
            dm = f32_of(&t["damage_multiplier"]),
            am = f32_of(&t["armor_multiplier"]),
            bat = t["base_attack_time"].as_u64().unwrap(),
            sw = f32_of(&t["speed_walk"]),
            sr = f32_of(&t["speed_run"]),
            det = f32_of(&t["detection_range"]),
        );
    }
    out
}

/// The keep-out rule: a player of a low camp's levels meets no mob red to them (vanilla's con
/// colour, [`RED_ABOVE`] levels over the camp's top) while there or on the way from the
/// Crossroads. An imported spawn that red is left out when its wander area reaches within
/// [`KEEP_OUT_YD`] of the camp's centre, the realm's view distance, or within [`ROUTE_CLEAR_YD`]
/// of the straight way from the Crossroads to it, beyond a red mob's aggro radius on a level-1
/// player.
const RED_ABOVE: u64 = 5;
const KEEP_OUT_YD: f64 = 100.0;
const ROUTE_CLEAR_YD: f64 = 40.0;

/// Whether the keep-out rule leaves the imported spawn `s` out: a low camp's own
/// `suppress_guids` lists it, or it is red to a camp near the camp or near the way to it.
fn kept_out(s: &Value, low: &Value) -> bool {
    let town = crossroads(low);
    let at = xy_of(s);
    let wander = s["wander_radius"].as_f64().unwrap_or(0.0);
    let level = s["level_min"].as_u64().unwrap();
    low["camps"].as_array().unwrap().iter().any(|c| {
        let center = xy(&c["center"]);
        c["suppress_guids"].as_array().unwrap().contains(&s["guid"])
            || level >= c["level_max"].as_u64().unwrap() + RED_ABOVE
                && (distance(at, center) - wander <= KEEP_OUT_YD
                    || to_segment(at, town, center) - wander <= ROUTE_CLEAR_YD)
    })
}

/// The inner ring: within this many yards of the Crossroads only the hand-placed camps stand,
/// levels 1–10. An imported spawn whose wander area reaches into it is left out.
pub const INNER_RING_YD: f64 = 600.0;
/// The inner ring's top level.
pub const INNER_RING_TOP: u64 = 10;
/// The Barrens' top level, Tier 1's cap.
pub const LEVEL_CAP: u64 = 30;
/// The Razorfen edge's quilboar, Razorfen Battleguard and Razorfen Thornweaver (vanilla's
/// 33–34 elites), kept as The Barrens' capstone at [`RAZORFEN_LEVELS`].
pub const RAZORFEN_QUILBOAR: [u64; 2] = [7873, 7874];
pub const RAZORFEN_LEVELS: [u64; 2] = [27, 30];
/// Creatures left out by name: the Death's Head Cultist and Geomancer (no cultist stands in The
/// Barrens), Ambassadors Bloodrage and Malcin, and the Wailing Caverns' Trigore the Lasher and
/// Boahn.
pub const LEFT_OUT: [u64; 6] = [7872, 7335, 7895, 12865, 3652, 3672];

/// How near another spawn stands to count as a neighbour, in yards.
pub const NEIGHBOURHOOD_YD: f64 = 120.0;
/// How far a spawn's level may sit from its neighbours' median before it is a stray: five levels,
/// where vanilla's con colour turns red (or grey, below).
pub const STRAY_LEVELS: f64 = 5.0;
/// The fewest neighbours that make a neighbourhood; a lone spawn is no stray.
pub const MIN_NEIGHBOURS: usize = 3;

/// Why the filter leaves an imported spawn out.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum Cut {
    /// Red to a low camp, near it or near the way to it.
    LowCamp,
    /// One of [`LEFT_OUT`].
    Named,
    /// Within [`INNER_RING_YD`] of the Crossroads.
    InnerRing,
    /// Above [`LEVEL_CAP`].
    OverCap,
    /// Far off its neighbours' level.
    Stray,
}

impl Cut {
    fn describe(self) -> String {
        match self {
            Cut::LowCamp => "red to a low camp's players near the camp or the way to it".into(),
            Cut::Named => {
                "by name: the Death's Head, the Ambassadors, Trigore the Lasher, Boahn".into()
            }
            Cut::InnerRing => {
                format!("within {INNER_RING_YD} yd of the Crossroads, the inner ring")
            }
            Cut::OverCap => format!("above level {LEVEL_CAP}"),
            Cut::Stray => format!(
                "strays, more than {STRAY_LEVELS} levels off the median of the spawns within \
                 {NEIGHBOURHOOD_YD} yd"
            ),
        }
    }
}

/// What the filter keeps of the dump's spawns, with the Razorfen quilboar retuned, and how many
/// it left out for each reason.
pub struct Filtered {
    pub kept: Vec<Value>,
    pub cut: std::collections::BTreeMap<Cut, usize>,
}

/// The rings. The imported spawns are left out, in this order, when red to a low camp, named in
/// [`LEFT_OUT`], in the inner ring, or above the level cap once the Razorfen quilboar are
/// retuned; then the strays among what stays (with the low camps as neighbours) are left out
/// until none is left.
pub fn filter(barrens: &Value, low: &Value) -> Filtered {
    let town = crossroads(low);
    let mut cut = std::collections::BTreeMap::new();
    let mut kept = Vec::new();
    for s in barrens["spawns"].as_array().unwrap() {
        let entry = s["entry"].as_u64().unwrap();
        let at = xy_of(s);
        let wander = s["wander_radius"].as_f64().unwrap_or(0.0);
        let mut s = s.clone();
        if RAZORFEN_QUILBOAR.contains(&entry) {
            s["level_min"] = RAZORFEN_LEVELS[0].into();
            s["level_max"] = RAZORFEN_LEVELS[1].into();
        }
        let why = if kept_out(&s, low) {
            Some(Cut::LowCamp)
        } else if LEFT_OUT.contains(&entry) {
            Some(Cut::Named)
        } else if distance(at, town) - wander <= INNER_RING_YD {
            Some(Cut::InnerRing)
        } else if s["level_max"].as_u64().unwrap() > LEVEL_CAP {
            Some(Cut::OverCap)
        } else {
            None
        };
        match why {
            Some(why) => *cut.entry(why).or_insert(0) += 1,
            None => kept.push(s),
        }
    }

    let templates = &barrens["templates"];
    let placed = |s: &Value, normal: bool| Placed {
        at: xy_of(s),
        levels: [
            s["level_min"].as_u64().unwrap(),
            s["level_max"].as_u64().unwrap(),
        ],
        normal,
    };
    let low_members: Vec<Placed> = low["camps"]
        .as_array()
        .unwrap()
        .iter()
        .flat_map(|c| c["members"].as_array().unwrap())
        .map(|m| placed(m, true))
        .collect();
    loop {
        let mut all: Vec<Placed> = kept
            .iter()
            .map(|s| {
                let rank = templates[s["entry"].as_u64().unwrap().to_string()]["rank"].as_str();
                placed(s, rank == Some("normal"))
            })
            .collect();
        all.extend(low_members.iter().cloned());
        let strays = strays(&all);
        if strays.is_empty() {
            break;
        }
        *cut.entry(Cut::Stray).or_insert(0) += strays.len();
        let mut i = 0;
        kept.retain(|_| {
            i += 1;
            !strays.contains(&(i - 1))
        });
    }
    Filtered { kept, cut }
}

/// A spawn as the stray rule sees it: where it stands, its levels, and whether it is a normal
/// creature (an elite, rare or boss is meant to stand above its neighbours).
#[derive(Clone, Debug)]
pub struct Placed {
    pub at: [f64; 2],
    pub levels: [u64; 2],
    pub normal: bool,
}

impl Placed {
    fn level(&self) -> f64 {
        (self.levels[0] + self.levels[1]) as f64 / 2.0
    }
}

/// The strays among `spawns`, by index: a normal creature more than [`STRAY_LEVELS`] off the
/// median level of the at least [`MIN_NEIGHBOURS`] spawns within [`NEIGHBOURHOOD_YD`] of it.
pub fn strays(spawns: &[Placed]) -> Vec<usize> {
    (0..spawns.len())
        .filter(|&i| {
            let me = &spawns[i];
            if !me.normal {
                return false;
            }
            let mut levels: Vec<f64> = spawns
                .iter()
                .enumerate()
                .filter(|&(j, o)| j != i && distance(o.at, me.at) <= NEIGHBOURHOOD_YD)
                .map(|(_, o)| o.level())
                .collect();
            if levels.len() < MIN_NEIGHBOURS {
                return false;
            }
            levels.sort_by(f64::total_cmp);
            let n = levels.len();
            let median = (levels[(n - 1) / 2] + levels[n / 2]) / 2.0;
            (me.level() - median).abs() > STRAY_LEVELS
        })
        .collect()
}

/// The Crossroads' centre, as the low camps' dump gives it.
pub fn crossroads(low: &Value) -> [f64; 2] {
    xy(&low["crossroads"])
}

fn xy(v: &Value) -> [f64; 2] {
    [v[0].as_f64().unwrap(), v[1].as_f64().unwrap()]
}

fn xy_of(s: &Value) -> [f64; 2] {
    [s["x"].as_f64().unwrap(), s["y"].as_f64().unwrap()]
}

fn distance(a: [f64; 2], b: [f64; 2]) -> f64 {
    (a[0] - b[0]).hypot(a[1] - b[1])
}

/// How far `p` is from the segment `a`–`b`.
fn to_segment(p: [f64; 2], a: [f64; 2], b: [f64; 2]) -> f64 {
    let (dx, dy) = (b[0] - a[0], b[1] - a[1]);
    let len2 = dx * dx + dy * dy;
    let t = if len2 == 0.0 {
        0.0
    } else {
        (((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / len2).clamp(0.0, 1.0)
    };
    distance(p, [a[0] + t * dx, a[1] + t * dy])
}

/// One spawn row.
fn row(out: &mut String, s: &Value, display: u64, camp: u64) {
    let z = if s["z"].is_null() {
        &s["z_hint"]
    } else {
        &s["z"]
    };
    let _ = writeln!(
        out,
        "  [{}, {}, {}, {}, {:?}, {:?}, {:?}, {:?}, {}, {:?}, {}],",
        s["guid"].as_u64().unwrap(),
        s["entry"].as_u64().unwrap(),
        s["level_min"].as_u64().unwrap(),
        s["level_max"].as_u64().unwrap(),
        f32_of(&s["x"]),
        f32_of(&s["y"]),
        f32_of(z),
        f32_of(&s["orientation"]),
        display,
        f32_of(&s["wander_radius"]),
        camp,
    );
}

/// The spawn's model: one of the template's displays, weighted by their probabilities and picked
/// by the spawn's guid, so a Kolkar camp shows its several models and every run shows the same.
fn pick_display(template: &Value, guid: u64, fallback: u64) -> u64 {
    let displays: Vec<(u64, u64)> = template["displays"]
        .as_array()
        .map(|ds| {
            ds.iter()
                .map(|d| {
                    (
                        d["display_id"].as_u64().unwrap(),
                        d["probability"].as_u64().unwrap_or(0),
                    )
                })
                .filter(|&(_, p)| p > 0)
                .collect()
        })
        .unwrap_or_default();
    let total: u64 = displays.iter().map(|&(_, p)| p).sum();
    if total == 0 {
        return fallback;
    }
    let mut roll = guid % total;
    for (display, p) in displays {
        if roll < p {
            return display;
        }
        roll -= p;
    }
    fallback
}

/// The template's most probable display, what a creature query answers.
fn most_likely_display(template: &Value) -> u64 {
    template["displays"]
        .as_array()
        .unwrap()
        .iter()
        .max_by_key(|d| d["probability"].as_u64().unwrap_or(0))
        .map(|d| d["display_id"].as_u64().unwrap())
        .unwrap()
}

/// Whether the entry's spawns are hostile to a player (every spawn of an entry shares its
/// faction template, so they agree).
fn reaction(barrens: &Value, entry: u64) -> bool {
    let reactions: Vec<&str> = barrens["spawns"]
        .as_array()
        .unwrap()
        .iter()
        .filter(|s| s["entry"].as_u64() == Some(entry))
        .map(|s| s["reaction"].as_str().unwrap())
        .collect();
    let hostile = reactions.first() == Some(&"hostile");
    assert!(
        reactions.iter().all(|&r| (r == "hostile") == hostile),
        "entry {entry}'s spawns disagree on their reaction"
    );
    hostile
}

/// `CreatureType.dbc`.
fn creature_type(name: &str) -> u32 {
    match name {
        "beast" => 1,
        "dragonkin" => 2,
        "demon" => 3,
        "elemental" => 4,
        "giant" => 5,
        "undead" => 6,
        "humanoid" => 7,
        "critter" => 8,
        "mechanical" => 9,
        "not_specified" => 10,
        other => panic!("unknown creature type {other}"),
    }
}

/// The creature query's rank (`CreatureEliteType`).
fn rank(name: &str) -> u32 {
    match name {
        "normal" => 0,
        "elite" => 1,
        "rare_elite" => 2,
        "world_boss" => 3,
        "rare" => 4,
        other => panic!("unknown rank {other}"),
    }
}

/// `creature_classlevelstats`' unit classes, as `content/mob_class_stats.toml` names them.
fn unit_class(id: u64) -> &'static str {
    match id {
        1 => "warrior",
        2 => "paladin",
        8 => "mage",
        other => panic!("unknown unit class {other}"),
    }
}

fn f32_of(v: &Value) -> f32 {
    v.as_f64().unwrap_or_else(|| panic!("a number: {v}")) as f32
}

/// A TOML basic string.
fn quoted(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

#[allow(dead_code)]
fn main() {
    let (barrens, low) = dumps();
    let out = output_path();
    std::fs::write(&out, convert(&barrens, &low)).expect("barrens.toml writes");
    println!("wrote {}", out.display());
}
