//! Writes `content/starting_outfits.toml`, each race's Warrior starting outfit, from the client's
//! `CharStartOutfit.dbc` (class 1, sex 0): the items a new character wears, with the display id
//! and inventory type the client dresses the create screen's model in. 1.12.1 ships no `Item.dbc`,
//! so this row is the client's only word on those two for each item.
//!
//! ```text
//! cargo run -p twilight-realm --example gen_outfits -- --data C:/path/to/WoW/Data
//! ```

use std::fmt::Write as _;
use std::path::PathBuf;

use benilla_formats::{open_chain, CharCreateCatalog};

/// `ChrRaces.dbc` ids 1..=8, as `content/starting_outfits.toml` names them.
const RACES: [(u8, &str); 8] = [
    (1, "human"),
    (2, "orc"),
    (3, "dwarf"),
    (4, "night_elf"),
    (5, "undead"),
    (6, "tauren"),
    (7, "gnome"),
    (8, "troll"),
];
const WARRIOR: u8 = 1;
const MALE: u8 = 0;

const HEADER: &str = "\
# Each race's Warrior starting outfit, from the client's CharStartOutfit.dbc (class 1, sex 0),
# generated by `cargo run -p twilight-realm --example gen_outfits -- --data <WoW/Data>`.
# A new character wears each `item` in its slot. The display id and inventory type are the
# client's own; tests/content.rs checks each item's template agrees with them.
";

fn main() {
    let data = data_dir();
    let mut chain = open_chain(&data).unwrap_or_else(|e| panic!("{}: {e:#}", data.display()));
    let catalog = CharCreateCatalog::load(&mut chain).expect("CharStartOutfit.dbc loads");

    let mut out = String::from(HEADER);
    for (race, name) in RACES {
        let items = catalog.start_outfit(race, WARRIOR, MALE);
        assert!(!items.is_empty(), "{name} has a Warrior outfit");
        let _ = writeln!(out, "\n{name} = [");
        for it in items {
            let _ = writeln!(
                out,
                "  {{ item = {}, display_id = {}, inventory_type = {} }},",
                it.item_id, it.display_id, it.inv_type
            );
        }
        out.push_str("]\n");
    }
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("content/starting_outfits.toml");
    std::fs::write(&path, out).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    println!("wrote {}", path.display());
}

/// `--data <dir>`, else `WOW_DATA`.
fn data_dir() -> PathBuf {
    let mut args = std::env::args().skip(1);
    while let Some(arg) = args.next() {
        if arg == "--data" {
            return args.next().expect("--data takes a directory").into();
        }
    }
    std::env::var_os("WOW_DATA")
        .map(PathBuf::from)
        .expect("pass --data <WoW/Data> or set WOW_DATA")
}
